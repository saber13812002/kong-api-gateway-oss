#!/usr/bin/env python3
"""Unit test for scripts/yaml2json.py against the exact YAML shape that
scripts/export.sh emits (nested configs, list-of-mappings, strings with
colons/quotes, empty containers, comments)."""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
Y2J = os.path.join(ROOT, "scripts", "yaml2json.py")

SAMPLE = """_format_version: "3.0"
services:
  - name: test-echo-svc
    protocol: http
    host: echo
    port: 9000
  - name: ai-gw-svc
    protocol: http
    host: 198.51.100.53
    port: 8000
routes:
  - name: test-echo-route
    paths:
      - /test-echo
    methods:
      - GET
      - POST
    strip_path: true
    response_buffering: true
    _service: test-echo-svc
  - name: fixed-ok-route
    paths:
      - /fixed-ok
    strip_path: false
    _service: t-resp-json-svc
consumers:
  - username: dev-app
    custom_id: app-dev-1
plugins:
  - name: request-transformer
    _service: t-req-header-svc
    config:
      replace:
        headers:
          - "X-Client-Type: modern"
  - name: oss-pre
    _service: t-pre-svc
    config:
      required_headers:
        - X-Api-Key
      correlation_id_header: X-Correlation-Id
      body_rename:
        customer_id: customerId
  - name: key-auth
    enabled: true
upstreams:
  - name: ai-backend
    slots: 32
    host_header: ai.example.com
    algorithm: round-robin
targets:
  - _upstream: ai-backend
    target: 198.51.100.53:8000
    weight: 100
  - _upstream: ai-backend
    target: 198.51.100.53:8001
    weight: 50
# generated by scripts/export.sh from http://127.0.0.1:18001 at 2026-10-20T00:00:00Z
"""

PASS = 0
FAIL = 0


def check(name, cond, extra=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print("PASS  %s  [%s]" % (name, extra))
    else:
        FAIL += 1
        print("FAIL  %s  [%s]" % (name, extra))


def main():
    tmp = "/tmp/y2j-sample.yml"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(SAMPLE)
    r = subprocess.run([sys.executable, Y2J, tmp], capture_output=True, text=True)
    if r.returncode != 0:
        print("FAIL  yaml2json exited nonzero\n", r.stdout, r.stderr)
        return 1
    with open(tmp + ".json", encoding="utf-8") as f:
        d = json.load(f)

    check("top-level _format_version == 3.0", d.get("_format_version") == "3.0", repr(d.get("_format_version")))
    svcs = d.get("services", [])
    check("2 services", len(svcs) == 2, len(svcs))
    check("svc[0] name", svcs[0].get("name") == "test-echo-svc", svcs[0].get("name"))
    check("svc[0] port int 9000", svcs[0].get("port") == 9000, repr(svcs[0].get("port")))
    check("svc[1] host (colon-free plain)", svcs[1].get("host") == "198.51.100.53", svcs[1].get("host"))

    routes = d.get("routes", [])
    check("2 routes", len(routes) == 2, len(routes))
    r0 = routes[0]
    check("route0 paths list", r0.get("paths") == ["/test-echo"], r0.get("paths"))
    check("route0 methods list", r0.get("methods") == ["GET", "POST"], r0.get("methods"))
    check("route0 strip_path bool true", r0.get("strip_path") is True, repr(r0.get("strip_path")))
    check("route0 response_buffering bool true", r0.get("response_buffering") is True, repr(r0.get("response_buffering")))
    check("route0 _service ref", r0.get("_service") == "test-echo-svc", r0.get("_service"))
    check("route1 strip_path bool false", routes[1].get("strip_path") is False, repr(routes[1].get("strip_path")))

    cons = d.get("consumers", [])
    check("1 consumer w/ custom_id", len(cons) == 1 and cons[0].get("custom_id") == "app-dev-1", cons)

    plugs = d.get("plugins", [])
    check("3 plugins", len(plugs) == 3, len(plugs))
    by = {p["name"]: p for p in plugs}
    rt = by.get("request-transformer", {})
    check("rt config.replace.headers[0] == 'X-Client-Type: modern'",
          rt.get("config", {}).get("replace", {}).get("headers") == ["X-Client-Type: modern"],
          rt.get("config"))
    pre = by.get("oss-pre", {})
    cfg = pre.get("config", {})
    check("oss-pre required_headers", cfg.get("required_headers") == ["X-Api-Key"], cfg.get("required_headers"))
    check("oss-pre body_rename nested", cfg.get("body_rename") == {"customer_id": "customerId"}, cfg.get("body_rename"))
    check("oss-pre correlation str", cfg.get("correlation_id_header") == "X-Correlation-Id", cfg.get("correlation_id_header"))
    check("key-auth enabled bool true", by.get("key-auth", {}).get("enabled") is True, by.get("key-auth"))

    ups = d.get("upstreams", [])
    check("1 upstream", len(ups) == 1, len(ups))
    check("upstream slots int", ups[0].get("slots") == 32, repr(ups[0].get("slots")))
    check("upstream host_header", ups[0].get("host_header") == "ai.example.com", ups[0].get("host_header"))

    tgs = d.get("targets", [])
    check("2 targets", len(tgs) == 2, len(tgs))
    check("target0 host:port string kept", tgs[0].get("target") == "198.51.100.53:8000", tgs[0].get("target"))
    check("target1 weight int 50", tgs[1].get("weight") == 50, repr(tgs[1].get("weight")))
    check("target _upstream ref", tgs[0].get("_upstream") == "ai-backend", tgs[0].get("_upstream"))

    print("\n%d passed, %d failed" % (PASS, FAIL))
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
